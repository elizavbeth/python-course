# Клас vs Об'єкт

# Клас (Class) — це креслення або шаблон. 
# Сам по собі він не є грою чи гравцем, він лише описує, які властивості та можливості вони матимуть.

# Об'єкт (Object / Instance) — це конкретний екземпляр, створений за цим кресленням.

class Player:
    def __init__(self, name):
        # Властивості (атрибути) об'єкта:
        self.name = name
        self.score = 0
        self.words_learned = []

    # Метод (функція всередині класу):
    def add_score(self, points):
        self.score += points
        print(f"Гравець {self.name} отримав(ла) {points} балів!")

# Розбір двох головних слів:

# def __init__(self, ...) — це конструктор. 
# Спеціальна функція, яка автоматично запускається в момент створення нового об'єкта. 
# В ній ми задаємо початкові властивості (атрибути).

# self — це посилання на поточний об'єкт. Через self об'єкт каже: "Це МОЄ ім'я (self.name) і МОЇ бали (self.score)".

# Створюємо двох ОКТРЕМЕМХ гравців за одним кресленням:
player1 = Player("Anna")
player2 = Player("Max")

# Викликаємо метод для першого гравця:
player1.add_score(15)  # Друк: Гравець Anna отримав(ла) 15 балів!

# Перевіряємо їхні бали:
print(player1.score)  # 15
print(player2.score)  # 0 (у Макса свої власні бали, вони не змінилися!)

# Три стовпи ООП
# Об'єктно-орієнтоване програмування тримається на трьох головних концепціях:

# Інкапсуляція — об'єднання даних та методів для роботи з ними всередині одного класу (те, що ми щойно зробили).
# Успадкування (Inheritance) — можливість створювати нові класи на основі існуючих, запозичуючи їхні властивості.
# Поліморфізм — можливість використовувати однаковий інтерфейс (методи) для різних об'єктів.