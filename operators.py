result = 50 // 4 + 3 ** 2 * 2 - 5 % 2
print(result)
# Порядок математичних операторів:
# Спочатку степінь, потім ділення націло, множення і ділення з остачею, потім додавання і віднімання.
# Результат 29

print(-7 // 2)
# -4
# Тут багато хто очікує -3.
# Чому -4?
# Тому що // — це не просто «відкинути все після крапки». 
# Це підлога (floor division) — результат округлюється вниз, до меншого цілого.

print(round(2.5))
# Важливіше знати, що round() не завжди поводиться як шкільне правило «.5 завжди вгору».

