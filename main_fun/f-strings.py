# f-string (або форматований рядок / formatted string literal).

# Навіщо потрібна f?
# Раніше, щоб підставити значення змінних у рядок, доводилося склеювати їх через плюс + або комами ,:

name = "Anna"
count = 3

# Спосіб 1 (склеювання плюсів — незручно, треба перетворювати числа в str):
print(name + " вивчив(ла) слів: " + str(count))

# Спосіб 2 (через кому — print додає зайві пробіли):
print(name, "вивчив(ла) слів:", count)


print("--------Приклади використання f:--------")

name = "max"
score = 45

# 1. Вставляємо змінні:
print(f"Гравець: {name}") 
# Друк: Гравець: max

# 2. Викликаємо методи прямо всередині фігурних дужок:
print(f"Гравець: {name.capitalize()}") 
# Друк: Гравець: Max

# 3. Виконуємо обчислення:
print(f"Наступний рівень через: {100 - score} балів") 
# Друк: Наступний рівень через: 55 балів

print("--------Округлення--------")

accuracy = 85.6789

# :.2f означає "2 знаки після коми для float (f)"
print(f"Твоя точність: {accuracy:.2f}%")
# Друк: Твоя точність: 85.68%

print("--------Вирівнювання та створення таблиць--------")

name = "Anna"
score = 150

# :<10 — вирівняти ліворуч у колонці шириною 10 символів
# :>5  — вирівняти праворуч у колонці шириною 5 символів
print(f"{name:<10} | {score:>5}")
# Друк: Anna       |   150

